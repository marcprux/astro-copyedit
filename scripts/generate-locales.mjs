import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

const root = new URL('../', import.meta.url);
const locales = {};
for (const locale of ['en', 'es']) {
  locales[locale] = JSON.parse(await readFile(new URL(`locales/${locale}.json`, root), 'utf8'));
}
const keys = Object.keys(locales.en).sort();
const placeholders = text => [...text.matchAll(/\{(\w+)\}/g)].map(m => m[1]).sort();
for (const messages of Object.values(locales)) {
  assert.deepEqual(Object.keys(messages).sort(), keys);
  for (const key of keys) assert.deepEqual(placeholders(messages[key]), placeholders(locales.en[key]));
}
const code = `// Generated by scripts/generate-locales.mjs. Edit locales/*.json instead.\nconst messages = ${JSON.stringify(locales, null, 2)};\nexport const supportedLocales = Object.freeze(Object.keys(messages));\nexport function resolveLocale(locale = 'en') {\n  const language = locale.toLowerCase().split('-')[0];\n  return supportedLocales.includes(language) ? language : 'en';\n}\nfunction format(key, locale, args) {\n  return messages[resolveLocale(locale)][key].replace(/\\{(\\w+)\\}/g, (_, name) => String(args[name]));\n}\nexport const str = Object.freeze({\n${keys.map(key => `  ${key}: (locale = 'en', args = {}) => format('${key}', locale, args),`).join('\n')}\n});\n`;
const output = new URL('src/generated/strings.js', root);
if (process.argv.includes('--check')) assert.equal(await readFile(output, 'utf8'), code, 'Generated localization is stale; run npm run generate.');
else await writeFile(output, code);
